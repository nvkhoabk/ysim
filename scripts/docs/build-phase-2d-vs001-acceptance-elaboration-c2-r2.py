def selected_rules(decision_id: str, option_id: str) -> list[dict]:
    data = json.loads(git_blob(GOVERNING, DECISION_PATH))
    decision_index = next(i for i, item in enumerate(data["decisions"]) if item["decision_id"] == decision_id)
    decision = data["decisions"][decision_index]
    option_index = next(i for i, item in enumerate(decision["options"]) if item["option_id"] == option_id)
    option = decision["options"][option_index]
    result = []
    for group, rules in option["canonical_rule_groups"].items():
        for index, rule in enumerate(rules):
            result.append({
                "group": group,
                "rule": rule,
                "authority_json_path": f"/decisions/{decision_index}/options/{option_index}/canonical_rule_groups/{group}/{index}",
            })
    return result


